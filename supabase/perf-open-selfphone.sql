-- ============================================================
--  كلٌّ يُدخل رقم جواله بنفسه عند التفعيل
--  ------------------------------------------------------------
--  ملف الهيكل ترك الجوال «لم يُسجَّل» — قيمةٌ ليست رقماً، فتمنع
--  التفعيل حتى يُدخل مديرُ المنصة الرقم. هذا الملف يرفع ذلك القفل
--  فيكتب كلُّ موظف رقمه في أول دخول.
--
--  ⚠️ الأثر الأمني — اقرئيه قبل التشغيل:
--     الجوال المسجَّل مسبقاً هو ما يُثبت أن مَن يفعّل الحساب صاحبُه.
--     برفعه يصير **أوّل من يعرف اسم الدخول ويفعّل الحساب يملكه**،
--     وأسماء الدخول هي بريد العمل — معروفة داخل المركز.
--     ولذلك: افتحيه حين يكون التفعيل جارياً، وراجعي القائمة بعده،
--     ثم أعيدي القفل على من لم يفعّل (الفقرة ٤).
--
--  آمن: لا يمسّ حساباً مفعَّلاً، ولا يمحو رقماً حقيقياً أُدخل من
--  صفحة المستخدمين. idempotent وليس فيه حذف بيانات.
-- ============================================================

-- ------------------------------------------------------------
--  ١) قبل: من سيُفتح له
-- ------------------------------------------------------------
select display_name as "الاسم", username as "اسم الدخول", phone as "الجوال المخزَّن"
  from public.perf_users
 where active and coalesce(pass_hash,'') = ''
   and coalesce(phone,'') <> ''
   and length(regexp_replace(phone,'[^0-9]','','g')) < 9
 order by display_name;

-- ------------------------------------------------------------
--  ٢) رفع القفل — للحسابات غير المفعَّلة وذات الجوال غير الصالح وحدها
-- ------------------------------------------------------------
update public.perf_users
   set phone = ''
 where active
   and coalesce(pass_hash,'') = ''                                  -- لم يفعّل بعد
   and coalesce(phone,'') <> ''                                     -- فيه قيمة
   and length(regexp_replace(phone,'[^0-9]','','g')) < 9;           -- وليست رقماً

-- ------------------------------------------------------------
--  ٣) بعد: الحالة الآن
-- ------------------------------------------------------------
select display_name as "الاسم", username as "اسم الدخول",
       case when coalesce(pass_hash,'') <> '' then 'مفعّل — لا يتأثر'
            when coalesce(phone,'') = '' then '✅ يكتب رقمه عند التفعيل'
            else 'رقمه مسجَّل: ينتهي بـ ' || right(regexp_replace(phone,'[^0-9]','','g'), 4)
       end as "الحالة"
  from public.perf_users
 where active
 order by (coalesce(pass_hash,'') <> ''), display_name;

