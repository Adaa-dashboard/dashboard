-- ============================================================
--  لماذا يقول «اسم المستخدم أو رقم الجوال غير صحيح»؟
--  ------------------------------------------------------------
--  يُشغَّل من SQL Editor. **الأول يقرأ ولا يغيّر شيئاً.**
--
--  شاشة «أول دخول» تطابق الجوال كاملاً، وشاشة «استعادة» تطابق
--  آخر أربعة أرقام — ومن له كلمة مرور أصلاً لا تنفعه شاشةُ أول
--  دخول، فيرى الرسالة نفسها وهو لم يخطئ.
-- ============================================================

-- ------------------------------------------------------------
--  ١) تشخيص كل حساب
-- ------------------------------------------------------------
select display_name as "الاسم",
       username     as "الحساب",
       case when coalesce(phone,'') = '' then '— لا يوجد —'
            else '…' || right(regexp_replace(phone,'[^0-9]','','g'), 4) end as "آخر ٤ أرقام",
       length(regexp_replace(coalesce(phone,''),'[^0-9]','','g')) as "عدد أرقامه",
       case when coalesce(pass_hash,'') <> '' then '✓' else '—' end as "له كلمة مرور",
       case when active then '✓' else '—' end as "نشط",
       case
         when not active
           then 'الحساب موقوف — فعّليه أولاً'
         when coalesce(phone,'') = ''
           then '✗ بلا جوال: لا أول دخول ولا استعادة. سجّلي جواله من «المستخدمون والصلاحيات»'
         when length(regexp_replace(phone,'[^0-9]','','g')) <> 12
           then '✗ الجوال المخزَّن ليس رقماً صحيحاً (أرقام عربية أو ناقص) — صحّحيه، أو شغّلي القسم ٢'
         when coalesce(pass_hash,'') <> ''
           then '⚠ له كلمة مرور: يدخل بها مباشرةً. وإن نسيها فمن «نسيت كلمة المرور» بآخر ٤ أرقام — لا من «أول دخول»'
         else '✓ جاهز لأول دخول: اسم المستخدم + الجوال كاملاً (05… أو 9665…)'
       end as "التشخيص"
  from public.perf_users
 order by active desc, display_name;

-- ------------------------------------------------------------
--  ٢) إصلاح الأرقام المخزَّنة بصيغة غير موحَّدة
--     (أرقام هندية ٠١٢ · مسافات · 05… · +966…)
--     يُعيد توحيدها بنفس دالة المنصة. لا يلمس الصحيح منها،
--     ولا يخترع رقماً لمن لا رقم له.
--     ⚠ احذفي السطرين التاليين إن أردتِ التشخيص وحده.
-- ------------------------------------------------------------
update public.perf_users
   set phone = public.perf_norm_phone(phone)
 where coalesce(phone,'') <> ''
   and phone <> public.perf_norm_phone(phone)
   and length(regexp_replace(public.perf_norm_phone(phone),'[^0-9]','','g')) = 12;

-- ------------------------------------------------------------
--  ٣) ما بقي معطوباً بعد الإصلاح — يُصحَّح يدوياً من الواجهة
-- ------------------------------------------------------------
select display_name as "الاسم", username as "الحساب",
       coalesce(nullif(phone,''), '— لا يوجد —') as "الجوال المخزَّن"
  from public.perf_users
 where active
   and (coalesce(phone,'') = ''
        or length(regexp_replace(phone,'[^0-9]','','g')) <> 12);
