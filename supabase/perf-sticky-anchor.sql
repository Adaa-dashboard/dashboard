-- ============================================================
--  الملاحظة اللاصقة تتذكّر البند الذي وُضعت عنده
--  ------------------------------------------------------------
--  كان الموضع نسبةً مئوية من مساحة الصفحة. النسبة تصمد أمام
--  اختلاف حجم الشاشة، ولا تصمد أمام اختلاف التخطيط: ثلاثة أعمدة
--  على الحاسوب تصير عموداً واحداً على الجوال، فالنقطة نفسها تقع
--  عند بندٍ آخر تماماً.
--  فصار يُحفظ مع الموضع عنوانُ البطاقة التي وُضعت عندها، وتُردّ
--  إليها في أي تخطيط. والنسبة تبقى احتياطاً إن لم تُوجد البطاقة.
--
--  idempotent وليس فيه حذف بيانات — الملاحظات القائمة تبقى
--  بموضعها القديم لأن العمود يُنشأ فارغاً.
--  يُشغَّل بعد perf-sticky.sql
-- ============================================================

alter table public.perf_stickies
  add column if not exists anchor text not null default '';

select id as "الملاحظة", page as "الصفحة",
       coalesce(nullif(anchor,''), '— بالموضع وحده —') as "عند بند",
       left(body, 40) as "النص"
  from public.perf_stickies
 where not done
 order by at desc;
