-- ============================================================
--  بيانات الربع الأول 2025 — جودة ملاحظات الأداء
--  ------------------------------------------------------------
--  يُشغَّل من SQL Editor مرة واحدة. idempotent، وليس فيه حذف.
--
--  الأرقام من عرض الربع الأول:
--    الشؤون الحكومية 93% (107) · البنية التحتية 86% (294)
--    المالي والاقتصادي 81% (47) · الخدمات الاجتماعية 78% (68)
--  مجموعها 516 عنصراً، ونسبتها المرجّحة بعدد العناصر
--    (107×93 + 294×86 + 47×81 + 68×78) ÷ 516 = 85.94 ⇒ **86%**
--  كما في العرض تماماً.
--
--  ونِسَب المعايير الأربعة (`p1..p4`) = 95 · 93 · 98 · 90 — وهي
--  نسب الإدارة لا نسب كل قطاع، فالعرض لا ينشرها مفصَّلةً بالقطاع.
--
--  وبهذا يصير الفرق بين الربعين في المنصة 79 − 86 = **−7%**،
--  وهو «▼7%» المذكور في عرض الربع الثاني.
--
--  جدول الجهات للربع الأول ليس هنا: أسماؤه في صور العرض لا في
--  ملفٍ، ونقلُها يدوياً يُدخل أخطاء إملائية تفصل الجهة عن نفسها
--  بين الربعين. يُدرَج متى وصل ملف العرض أو ملف التقييم.
-- ============================================================

insert into public.perf_items (section, id, ord, data) values
 ('notesq', 'nq-q1-s1', 1, '{"quarter": "الربع الأول 2025", "sector": "الشؤون الحكومية", "total": 107, "pct": 93, "p1": 95, "p2": 93, "p3": 98, "p4": 90}'::jsonb),
 ('notesq', 'nq-q1-s2', 2, '{"quarter": "الربع الأول 2025", "sector": "البنية التحتية", "total": 294, "pct": 86, "p1": 95, "p2": 93, "p3": 98, "p4": 90}'::jsonb),
 ('notesq', 'nq-q1-s3', 3, '{"quarter": "الربع الأول 2025", "sector": "المالي والاقتصادي", "total": 47, "pct": 81, "p1": 95, "p2": 93, "p3": 98, "p4": 90}'::jsonb),
 ('notesq', 'nq-q1-s4', 4, '{"quarter": "الربع الأول 2025", "sector": "الخدمات الاجتماعية", "total": 68, "pct": 78, "p1": 95, "p2": 93, "p3": 98, "p4": 90}'::jsonb)
on conflict (section, id) do update set data = excluded.data, ord = excluded.ord;

-- تحقّق: الربعان ونسبتاهما والفرق بينهما
with q as (
  select data->>'quarter' qt,
         sum((data->>'total')::numeric) n,
         sum((data->>'total')::numeric * (data->>'pct')::numeric) ok
    from public.perf_items
   where section = 'notesq' and data->>'row' is null
   group by 1
)
select qt as "الربع", n::int as "عدد العناصر", round(ok/nullif(n,0)) as "نسبة الالتزام ٪",
       round(ok/nullif(n,0)) - lag(round(ok/nullif(n,0))) over (order by qt) as "الفرق عن السابق"
  from q order by qt;
