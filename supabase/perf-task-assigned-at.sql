-- ============================================================
--  تاريخ ورود التكليف — عمودٌ جديد في perf_tasks
--  ------------------------------------------------------------
--  يُشغَّل مرة واحدة من SQL Editor. idempotent وبلا حذف.
--
--  السبب: «جديد» في التقرير كان يُحسب من `created_at` أي تاريخ
--  إدخال التكليف في المنصة. وتكليفٌ ورد قبل شهور ويُدخَل اليوم
--  يظهر «جديداً» وهو ليس كذلك — فإن مضى موعده فهو متأخر، وإلا
--  فهو قيد العمل.
--
--  العمود يبقى فارغاً لما أُدخل سابقاً، وعندها يُقرأ تاريخ
--  الإدخال كما كان — فلا يتغيّر شيءٌ إلا لمن كتبت له تاريخاً.
-- ============================================================

alter table public.perf_tasks
  add column if not exists assigned_at date;

comment on column public.perf_tasks.assigned_at is
  'تاريخ ورود التكليف للمركز — غير created_at (تاريخ الإدخال)';

-- تحقّق
select count(*) filter (where assigned_at is not null) as "له تاريخ ورود",
       count(*)                                        as "إجمالي التكاليف"
  from public.perf_tasks
 where kind = 'assignment';
