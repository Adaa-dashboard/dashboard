export type GoalRow = Goal & {
  /** المحقّق — null إن لم يُرصد بعد */
  got: number | null;
  /** نسبة التحقيق من المستهدف، مسقوفةً بـ 100 */
  pct: number | null;
  /** مصدرُ الرقم كما يُعرض */
  src: string;
};

/** الوزن المرجَّح: ما رُصد وحده يدخل الحساب — والمؤشر الذي لم
    يُرصد بعد لا يُحتسب صفراً فيُظلم صاحبه، بل يُقال كم رُصد. */
export function goalsScore(rows: GoalRow[]): { pct: number | null; have: number; weight: number } {
  const have = rows.filter((r) => r.pct !== null);
  const w = have.reduce((a, r) => a + r.weight, 0);
  if (!w) return { pct: null, have: 0, weight: 0 };
  const s = have.reduce((a, r) => a + (r.pct as number) * r.weight, 0);
  return { pct: Math.round(s / w), have: have.length, weight: w };
}
