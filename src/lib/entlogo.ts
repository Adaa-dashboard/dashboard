/* ============================================================
   وجهُ الجهة — شعارٌ إن وُجد، وإلا حرفان من اسمها
   ------------------------------------------------------------
   أكثر الجهات بلا ملف شعار، والمربّع الفارغ أسوأ من لا شيء.
   فلكل جهة حرفان بلونٍ ثابت مشتقٍّ من اسمها: يُعرف بلمحة، ولا
   يتغيّر بين شاشة وأخرى ولا بين جلسة وأخرى.
   يشترك فيه: صفحة الجهات · بطاقات جلسات مراجعة الأداء.
   ============================================================ */

/** كلماتٌ لا تُؤخذ منها الحروف — «الهيئة العامة…» حرفاها من «هيئة» و«عامة» */
const SKIP = new Set(["ال", "في", "من", "على", "و", "عن", "مع"]);

export function initials(name: string): string {
  const w = String(name || "")
    .replace(/[«»"'()]/g, " ")
    .split(/\s+/)
    .filter((x) => x && !SKIP.has(x));
  /* «الإسكان» حرفها س لا ا — أداة التعريف لا تعرّف شيئاً */
  const head = (x: string) => (x.startsWith("ال") && x.length > 2 ? x[2] : x[0]);
  if (!w.length) return "؟";
  return w.length === 1 ? head(w[0]) : head(w[0]) + head(w[1]);
}

const TONES = ["#016b5f", "#1a9d5c", "#2f7fd1", "#7a5cd1", "#c9a020", "#d34a4a", "#e0971a", "#5aaba2"];

/** لونٌ ثابت من الاسم — نفس الجهة نفس اللون دائماً */
export function toneOf(s: string): string {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return TONES[h % TONES.length];
}
